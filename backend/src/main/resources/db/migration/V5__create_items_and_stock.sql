CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    item_type VARCHAR(20) NOT NULL,
    minimum_quantity INTEGER,
    unit VARCHAR(30) DEFAULT 'unidades',
    clothing_size VARCHAR(30),
    clothing_color VARCHAR(50),
    last_worn_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    archived_at TIMESTAMPTZ,
    CONSTRAINT items_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT chk_item_type CHECK (item_type IN ('CONSUMABLE', 'DURABLE')),
    CONSTRAINT chk_minimum_quantity_positive CHECK (minimum_quantity IS NULL OR minimum_quantity >= 0),
    CONSTRAINT chk_minimum_quantity_only_consumable CHECK (
        (item_type = 'CONSUMABLE') OR (item_type = 'DURABLE' AND minimum_quantity IS NULL)
    )
);

CREATE INDEX idx_items_household ON items(household_id);
CREATE INDEX idx_items_category ON items(category_id);
CREATE INDEX idx_items_archived ON items(archived_at);

CREATE TABLE stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    location_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL DEFAULT 0,
    batch_number VARCHAR(50),
    expiration_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_stock_quantity_non_negative CHECK (quantity >= 0)
);

CREATE INDEX idx_stock_item ON stock(item_id);
CREATE INDEX idx_stock_location ON stock(location_id);
CREATE INDEX idx_stock_expiration ON stock(expiration_date);

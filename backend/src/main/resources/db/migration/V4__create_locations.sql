CREATE TABLE locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households(id) ON DELETE CASCADE,
    parent_id BIGINT REFERENCES locations(id) ON DELETE RESTRICT,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    archived_at TIMESTAMPTZ,
    CONSTRAINT locations_name_not_blank CHECK (btrim(name) <> '')
);

CREATE INDEX idx_locations_household ON locations(household_id);
CREATE INDEX idx_locations_parent ON locations(parent_id);

-- Unicidad de nombre de ubicación activa dentro del mismo padre o raíz en el mismo hogar
CREATE UNIQUE INDEX uq_locations_active_same_parent ON locations(household_id, parent_id, lower(btrim(name)))
WHERE archived_at IS NULL AND parent_id IS NOT NULL;

CREATE UNIQUE INDEX uq_locations_active_root ON locations(household_id, lower(btrim(name)))
WHERE archived_at IS NULL AND parent_id IS NULL;

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    movement_type VARCHAR(20) NOT NULL,
    quantity INTEGER NOT NULL,
    source_location_id BIGINT REFERENCES locations(id) ON DELETE RESTRICT,
    destination_location_id BIGINT REFERENCES locations(id) ON DELETE RESTRICT,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_movement_type CHECK (movement_type IN ('ENTRY', 'EXIT', 'TRANSFER', 'ADJUSTMENT')),
    CONSTRAINT chk_movement_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_movements_item ON inventory_movements(item_id);
CREATE INDEX idx_movements_created ON inventory_movements(created_at);

CREATE TABLE shopping_list_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households(id) ON DELETE CASCADE,
    item_id BIGINT REFERENCES items(id) ON DELETE SET NULL,
    name VARCHAR(150) NOT NULL,
    pending_quantity INTEGER NOT NULL DEFAULT 1,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT shopping_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT chk_shopping_quantity_non_negative CHECK (pending_quantity >= 0),
    CONSTRAINT chk_shopping_status CHECK (status IN ('PENDING', 'COMPLETED'))
);

CREATE INDEX idx_shopping_household ON shopping_list_entries(household_id);
CREATE INDEX idx_shopping_status ON shopping_list_entries(status);
